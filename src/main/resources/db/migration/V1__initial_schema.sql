-- ---------------------------------------------------------------------
-- genre: kleine Stammdatentabelle
-- ---------------------------------------------------------------------
CREATE TABLE genre (
                       id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(50) NOT NULL,
                       CONSTRAINT uq_genre_name UNIQUE (name),
                       CONSTRAINT ck_genre_name_nicht_leer CHECK (length(trim(name)) > 0)
);

-- ---------------------------------------------------------------------
-- spiel: Katalog. anzahl_bewertungen / rating_summe sind bewusste Redundanz
-- (siehe Projektskizze), damit die Spielübersicht nicht über alle Einträge
-- aggregieren muss.
-- ---------------------------------------------------------------------
CREATE TABLE spiel (
                       id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       genre_id           BIGINT       NOT NULL REFERENCES genre (id),
                       titel              VARCHAR(200) NOT NULL,
                       erscheinungsjahr   SMALLINT,
                       aktiv              BOOLEAN      NOT NULL DEFAULT TRUE,
                       anzahl_bewertungen INTEGER      NOT NULL DEFAULT 0,
                       rating_summe       INTEGER      NOT NULL DEFAULT 0,
                       CONSTRAINT ck_spiel_titel_nicht_leer CHECK (length(trim(titel)) > 0),
                       CONSTRAINT ck_spiel_jahr             CHECK (erscheinungsjahr BETWEEN 1950 AND 2100),
                       CONSTRAINT ck_spiel_anzahl           CHECK (anzahl_bewertungen >= 0),
    -- Jede Bewertung liegt zwischen 1 und 10, also muss die Summe dazu passen
                       CONSTRAINT ck_spiel_summe_plausibel  CHECK (rating_summe BETWEEN anzahl_bewertungen
                           AND anzahl_bewertungen * 10)
);

-- Titel eindeutig, unabhängig von Gross-/Kleinschreibung ("Zelda" = "zelda")
CREATE UNIQUE INDEX uq_spiel_titel_lower ON spiel (lower(titel));

-- ---------------------------------------------------------------------
-- spieler: Profil ohne Login
-- ---------------------------------------------------------------------
CREATE TABLE spieler (
                         id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         benutzername VARCHAR(50) NOT NULL,
                         erstellt_am  TIMESTAMPTZ NOT NULL DEFAULT now(),
                         CONSTRAINT uq_spieler_benutzername UNIQUE (benutzername),
                         CONSTRAINT ck_spieler_name_nicht_leer CHECK (length(trim(benutzername)) > 0)
);

-- ---------------------------------------------------------------------
-- eintrag: Spiel in der Liste eines Spielers (löst n:m auf)
-- ---------------------------------------------------------------------
CREATE TABLE eintrag (
                         id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         spieler_id       BIGINT       NOT NULL REFERENCES spieler (id),
                         spiel_id         BIGINT       NOT NULL REFERENCES spiel (id),
                         status           VARCHAR(20)  NOT NULL,
                         rating           SMALLINT,
                         bewertungstext   VARCHAR(2000),
                         spielzeit_std    NUMERIC(6, 1),
                         gestartet_am     DATE,
                         abgeschlossen_am DATE,
                         version          BIGINT       NOT NULL DEFAULT 0,
                         aktualisiert_am  TIMESTAMPTZ  NOT NULL DEFAULT now(),

                         CONSTRAINT uq_eintrag_spieler_spiel UNIQUE (spieler_id, spiel_id),
                         CONSTRAINT ck_eintrag_status CHECK (status IN ('GEPLANT', 'AM_SPIELEN', 'GESPIELT', 'ABGEBROCHEN')),
                         CONSTRAINT ck_eintrag_rating CHECK (rating BETWEEN 1 AND 10),
                         CONSTRAINT ck_eintrag_rating_pflicht CHECK (status NOT IN ('GESPIELT', 'ABGEBROCHEN') OR rating IS NOT NULL),
                         CONSTRAINT ck_eintrag_spielzeit CHECK (spielzeit_std >= 0),
                         CONSTRAINT ck_eintrag_datum CHECK (abgeschlossen_am IS NULL OR gestartet_am IS NULL
                             OR abgeschlossen_am >= gestartet_am),
                         CONSTRAINT ck_eintrag_abschluss_status CHECK (abgeschlossen_am IS NULL
                             OR status IN ('GESPIELT', 'ABGEBROCHEN'))
);

-- ---------------------------------------------------------------------
-- statuswechsel: Verlauf. Wird ein Eintrag gelöscht, verschwindet
-- auch sein Verlauf (ON DELETE CASCADE).
-- ---------------------------------------------------------------------
CREATE TABLE statuswechsel (
                               id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               eintrag_id   BIGINT      NOT NULL REFERENCES eintrag (id) ON DELETE CASCADE,
                               alter_status VARCHAR(20),
                               neuer_status VARCHAR(20) NOT NULL,
                               geaendert_am TIMESTAMPTZ NOT NULL DEFAULT now(),
                               CONSTRAINT ck_sw_alter_status CHECK (alter_status IN ('GEPLANT', 'AM_SPIELEN', 'GESPIELT', 'ABGEBROCHEN')),
                               CONSTRAINT ck_sw_neuer_status CHECK (neuer_status IN ('GEPLANT', 'AM_SPIELEN', 'GESPIELT', 'ABGEBROCHEN')),
    -- ein "Wechsel" auf denselben Status ist kein Wechsel
                               CONSTRAINT ck_sw_unterschiedlich CHECK (alter_status IS DISTINCT FROM neuer_status)
    );

-- PostgreSQL legt für Fremdschlüssel KEINEN Index automatisch an.
-- Dieser wird für "Verlauf eines Eintrags laden" und das CASCADE-Löschen gebraucht.
CREATE INDEX ix_statuswechsel_eintrag ON statuswechsel (eintrag_id);